import React, { useState, useRef } from 'react';
import { uploadArtifacts, setApiBaseUrl, getApiBaseUrl, healthCheck } from '../services/api';

function Settings({
  runId,
  setRunId,
  featureRunId,
  setFeatureRunId,
  onPipelineComplete
}) {
  const [apiUrl, setApiUrl] = useState(getApiBaseUrl());
  const [files, setFiles] = useState([]);
  const [runPipeline, setRunPipeline] = useState(true);
  const [uploading, setUploading] = useState(false);
  const [uploadResult, setUploadResult] = useState(null);
  const [apiStatus, setApiStatus] = useState(null);
  const fileInputRef = useRef(null);
  const [lastRunId, setLastRunId] = useState(null);

  const handleApiUrlChange = (e) => {
    const url = e.target.value;
    setApiUrl(url);
    setApiBaseUrl(url);
  };

  const checkApiHealth = async () => {
    try {
      const result = await healthCheck();
      setApiStatus({ ok: true, message: `Connected: ${result.service}` });
    } catch (error) {
      setApiStatus({ ok: false, message: 'Failed to connect to API' });
    }
  };

  const handleFileChange = (e) => {
    const selectedFiles = Array.from(e.target.files);
    setFiles(selectedFiles);
  };

  const handleDrop = (e) => {
    e.preventDefault();
    const droppedFiles = Array.from(e.dataTransfer.files);
    setFiles(droppedFiles);
  };

  const handleDragOver = (e) => {
    e.preventDefault();
  };

  const removeFile = (index) => {
    setFiles(files.filter((_, i) => i !== index));
  };

  const handleUpload = async () => {
    if (files.length === 0) {
      alert('Please select files to upload');
      return;
    }

    setUploading(true);
    setUploadResult(null);

    try {
      // Pass empty strings — backend will generate the actual run ID from UTC timestamp
      const result = await uploadArtifacts(files, '', '', runPipeline);

      const actualRunId = result.context_run_id || null;
      const actualFeatId = result.feature_run_id || null;

      setUploadResult({
        ok: result.ok,
        message: result.ok
          ? `✅ Pipeline complete! New Run ID: ${actualRunId}`
          : '❌ Pipeline failed — check details below',
        details: result,
        returnedRunId: actualRunId,
      });

      if (result.ok && actualRunId) {
        // Use exactly what the backend returned — no timezone guessing
        setRunId(actualRunId);
        setLastRunId(actualRunId);
        if (actualFeatId) setFeatureRunId(actualFeatId);
      }

      setFiles([]);
    } catch (error) {
      setUploadResult({
        ok: false,
        message: 'Upload failed: ' + (error.message || 'Unknown error'),
        details: null
      });
    }

    setUploading(false);
  };

  return (
    <div className="main-container">
      <div className="page-header">
        <h1 className="page-title">Settings and Pipeline</h1>
      </div>

      {/* API Configuration */}
      <div className="section">
        <h2 className="section-title">API Configuration</h2>
        <div className="input-group">
          <label className="input-label">API Base URL</label>
          <div style={{ display: 'flex', gap: '10px' }}>
            <input
              className="input-field"
              value={apiUrl}
              onChange={handleApiUrlChange}
              placeholder="http://127.0.0.1:8000"
              style={{ flex: 1 }}
            />
            <button className="btn btn-secondary" onClick={checkApiHealth}>
              Test Connection
            </button>
          </div>
          {apiStatus && (
            <div style={{
              marginTop: '10px',
              padding: '10px',
              background: apiStatus.ok ? '#98E4C1' : '#FB5E4C',
              border: '1px solid black',
              fontWeight: '600'
            }}>
              {apiStatus.message}
            </div>
          )}
        </div>
      </div>

      {/* Upload Run Info */}
      <div className="section">
        <h2 className="section-title">Upload Run ID</h2>
        <p style={{ color: '#333', fontSize: '14px', marginBottom: '10px' }}>
          Each upload automatically gets a <strong>unique timestamped Run ID</strong> (generated by the server).
          The dashboard will switch to show <strong>only that upload's data</strong>.
        </p>
        <div style={{ background: '#F7CC66', border: '1px solid black', borderRadius: '5px', padding: '12px 16px', fontSize: '14px' }}>
          Currently viewing: <strong>{runId}</strong>
          {lastRunId && <span style={{ marginLeft: '16px', color: '#555' }}>← last upload: <strong>{lastRunId}</strong></span>}
        </div>
      </div>

      {/* File Upload */}
      <div className="section">
        <h2 className="section-title">Artifact Upload</h2>
        <p style={{ marginBottom: '15px', color: '#333' }}>
          Upload verification logs, coverage reports, and other artifacts (.log, .txt, .json, .xml, .yaml, .hjson, .rpt)
        </p>

        <div
          className="upload-zone"
          onDrop={handleDrop}
          onDragOver={handleDragOver}
          onClick={() => fileInputRef.current?.click()}
          style={{
            border: '2px dashed black',
            padding: '40px',
            textAlign: 'center',
            cursor: 'pointer',
            background: '#F7CC66',
            marginBottom: '20px'
          }}
        >
          <div style={{ fontSize: '24px', marginBottom: '10px' }}>Drop files here or click to browse</div>
          <div style={{ fontSize: '14px', color: '#666' }}>
            Supports: .log, .txt, .json, .xml, .yaml, .yml, .hjson, .rpt, .cfg
          </div>
          <input
            ref={fileInputRef}
            type="file"
            multiple
            onChange={handleFileChange}
            accept=".log,.txt,.json,.xml,.yaml,.yml,.hjson,.rpt,.cfg"
            style={{ display: 'none' }}
          />
        </div>

        {files.length > 0 && (
          <div className="file-list" style={{ marginBottom: '20px' }}>
            <h3>Selected Files ({files.length})</h3>
            <div style={{
              maxHeight: '200px',
              overflowY: 'auto',
              border: '1px solid black',
              background: 'white'
            }}>
              {files.map((file, index) => (
                <div key={index} style={{
                  display: 'flex',
                  justifyContent: 'space-between',
                  alignItems: 'center',
                  padding: '8px 12px',
                  borderBottom: '1px solid #ddd'
                }}>
                  <span>{file.name} ({(file.size / 1024).toFixed(1)} KB)</span>
                  <button
                    onClick={(e) => { e.stopPropagation(); removeFile(index); }}
                    style={{
                      background: '#FB5E4C',
                      border: '1px solid black',
                      padding: '2px 8px',
                      cursor: 'pointer',
                      fontWeight: '600'
                    }}
                  >
                    X
                  </button>
                </div>
              ))}
            </div>
          </div>
        )}

        <div style={{ display: 'flex', alignItems: 'center', gap: '20px', marginBottom: '20px' }}>
          <label style={{ display: 'flex', alignItems: 'center', gap: '8px', cursor: 'pointer' }}>
            <input
              type="checkbox"
              checked={runPipeline}
              onChange={(e) => setRunPipeline(e.target.checked)}
              style={{ width: '20px', height: '20px' }}
            />
            <span style={{ fontWeight: '600' }}>Run full pipeline after upload</span>
          </label>
        </div>

        <button
          className="btn btn-primary"
          onClick={handleUpload}
          disabled={uploading || files.length === 0}
          style={{ width: '100%', padding: '15px', fontSize: '18px' }}
        >
          {uploading ? 'Uploading and Processing...' : 'Upload and Process Artifacts'}
        </button>

        {uploading && (
          <div style={{
            marginTop: '20px',
            padding: '20px',
            background: '#9AD7FD',
            border: '1px solid black',
            textAlign: 'center'
          }}>
            <div style={{ fontSize: '18px', fontWeight: '600' }}>Processing Pipeline...</div>
            <div style={{ marginTop: '10px' }}>This may take several minutes. Please wait.</div>
          </div>
        )}

        {uploadResult && (
          <div style={{
            marginTop: '20px',
            padding: '20px',
            background: uploadResult.ok ? '#98E4C1' : '#FB5E4C',
            border: '1px solid black'
          }}>
            <div style={{ fontSize: '18px', fontWeight: '600', marginBottom: '10px' }}>
              {uploadResult.message}
            </div>
            {uploadResult.ok && (
              <button
                className="btn btn-primary"
                onClick={onPipelineComplete}
                style={{ marginBottom: '15px', fontSize: '16px', padding: '10px 24px' }}
              >
                📊 View Updated Dashboard →
              </button>
            )}
            {uploadResult.details && (
              <details>
                <summary style={{ cursor: 'pointer', fontWeight: '600', marginBottom: '8px' }}>Pipeline Details</summary>
                <div style={{
                  background: 'white',
                  padding: '10px',
                  border: '1px solid black',
                  maxHeight: '300px',
                  overflowY: 'auto',
                  fontFamily: 'monospace',
                  fontSize: '12px',
                  whiteSpace: 'pre-wrap'
                }}>
                  {JSON.stringify(uploadResult.details, null, 2)}
                </div>
              </details>
            )}
          </div>
        )}
      </div>

      {/* Pipeline Info */}
      <div className="section" style={{ marginTop: '30px' }}>
        <h2 className="section-title">Pipeline Steps</h2>
        <div style={{
          background: 'white',
          border: '1px solid black',
          padding: '20px'
        }}>
          <p>When you upload files with "Run full pipeline" enabled, the following steps execute:</p>
          <ol style={{ paddingLeft: '20px', marginTop: '15px', lineHeight: '2' }}>
            <li><strong>Parse Logs</strong> - Extract tests, modules, failures, coverage from uploaded files</li>
            <li><strong>Build Context</strong> - Calculate risk scores for each module</li>
            <li><strong>Feature Engineering</strong> - Create ML feature vectors</li>
            <li><strong>Train Failure Model</strong> - Train LightGBM model for failure prediction</li>
            <li><strong>Train Coverage Model</strong> - Train model for coverage prioritization</li>
            <li><strong>Debug Analysis</strong> - Run TF-IDF similarity for debug prioritization</li>
          </ol>
        </div>
      </div>
    </div>
  );
}

export default Settings;
